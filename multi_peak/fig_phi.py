def monomorphic_first_step_angle(
    N,
    unchanged_probability,
):
    """
    Finite-N monomorphic first-step approximation.

    Mutated offspring are assumed to be distinct.
    """
    denominator_squared = (
        unchanged_probability**2
        + (
            1.0
            - unchanged_probability
        )
        / N
    )

    cosine_value = (
        unchanged_probability
        / math.sqrt(
            denominator_squared
        )
    )

    cosine_value = min(
        max(
            cosine_value,
            -1.0,
        ),
        1.0,
    )

    return math.acos(
        cosine_value
    )


def stationary_peak_fraction(
    F,
    unchanged_probability,
    background_fitness=1.0,
):
    """
    Deterministic single-peak stationary fraction.

    For background fitness b:

        x* = (F p0 - b)/(F - b).

    Returns zero when the peak is not supercritical.
    """
    if F <= background_fitness:
        return 0.0

    numerator = (
        F * unchanged_probability
        - background_fitness
    )

    denominator = (
        F
        - background_fitness
    )

    if numerator <= 0.0:
        return 0.0

    return min(
        max(
            numerator / denominator,
            0.0,
        ),
        1.0,
    )


def stationary_single_peak_angle(
    F,
    N,
    unchanged_probability,
    background_fitness=1.0,
):
    """
    Finite-N stationary peak-plus-singleton closure.

    The background contains N(1-x*) distinct singleton genotypes.
    """
    x_star = stationary_peak_fraction(
        F=F,
        unchanged_probability=unchanged_probability,
        background_fitness=background_fitness,
    )

    if x_star <= 0.0:
        return math.acos(
            unchanged_probability
        )

    peak_abundance = (
        N * x_star
    )

    background_individuals = (
        N * (1.0 - x_star)
    )

    total_weight = (
        F * peak_abundance
        + background_fitness
        * background_individuals
    )

    S2 = (
        peak_abundance**2
        + background_individuals
    )

    A1 = (
        F * peak_abundance**2
        + background_fitness
        * background_individuals
    )

    A2 = (
        F**2
        * peak_abundance**2
        + background_fitness**2
        * background_individuals
    )

    numerator = (
        math.sqrt(N)
        * unchanged_probability
        * A1
        / total_weight
    )

    denominator = (
        math.sqrt(S2)
        * math.sqrt(
            1.0
            + (
                N - 1
            )
            * unchanged_probability**2
            * A2
            / total_weight**2
        )
    )

    cosine_value = (
        numerator
        / denominator
    )

    cosine_value = min(
        max(
            cosine_value,
            -1.0,
        ),
        1.0,
    )

    return math.acos(
        cosine_value
    )


def two_component_angle(
    x_previous,
    x_current,
):
    """
    Angle between vectors (1-x_previous, x_previous) and
    (1-x_current, x_current).
    """
    vector_previous = np.array(
        [
            1.0 - x_previous,
            x_previous,
        ],
        dtype=float,
    )

    vector_current = np.array(
        [
            1.0 - x_current,
            x_current,
        ],
        dtype=float,
    )

    cosine_value = float(
        np.dot(
            vector_previous,
            vector_current,
        )
        / (
            np.linalg.norm(
                vector_previous
            )
            * np.linalg.norm(
                vector_current
            )
        )
    )

    cosine_value = float(
        np.clip(
            cosine_value,
            -1.0,
            1.0,
        )
    )

    return math.acos(
        cosine_value
    )


