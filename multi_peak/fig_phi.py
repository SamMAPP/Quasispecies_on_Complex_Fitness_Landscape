def simulation_signature(simulation_base):
    """Remove the iteration number from a simulation base filename."""
    return ITERATION_PATTERN.sub(
        "_iteration_*",
        str(simulation_base),
    )


def compact_signature_hash(signature):
    """Stable short identifier used in output filenames."""
    return hashlib.blake2b(
        signature.encode("utf-8"),
        digest_size=6,
        person=b"m4a30phith",
    ).hexdigest()


def extract_parameter(
    pattern,
    signature,
    group_name,
    cast=None,
):
    """Extract one optional parameter from the filename signature."""
    match = pattern.search(signature)

    if match is None:
        return None

    value = match.group(group_name)

    return value if cast is None else cast(value)


